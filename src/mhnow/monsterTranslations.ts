// 不切「・」—— 那是魔物名的一部分（テオ・テスカトル、メル・ゼナ）。
const PAIR_SEPARATOR = /\s*[,、，]\s*/;
const one = (name: string) => names[name] ?? name.replaceAll("亜種", "亞種").replaceAll("希少種", "稀少種");
export function monsterNameZh(name: string): string {
  return name.split(PAIR_SEPARATOR).map(one).join("、");
}
